/**
 * Migrations are checked-in SQL files (spec 6.2), but Metro cannot import .sql,
 * so they are embedded into a generated TS module that ships in the app bundle.
 * `pnpm --filter @nt/db gen` regenerates it; a test fails if it drifts.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.join(import.meta.dirname, '..');
const dir = path.join(root, 'migrations');

export function renderMigrations() {
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const entries = files.map((file) => ({
    name: file.replace(/\.sql$/, ''),
    sql: readFileSync(path.join(dir, file), 'utf8'),
  }));
  return `// Generated by scripts/build-migrations.mjs — do not edit by hand.
// Source of truth: packages/db/migrations/*.sql

export interface Migration {
  name: string;
  sql: string;
}

export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(entries, null, 2)};
`;
}

if (process.argv[1] === import.meta.filename) {
  const out = path.join(root, 'src', 'migrations.generated.ts');
  writeFileSync(out, renderMigrations());
  console.log(`✓ ${path.relative(root, out)}`);
}
